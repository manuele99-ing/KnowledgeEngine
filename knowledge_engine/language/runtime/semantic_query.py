from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np


@dataclass(frozen=True, slots=True)
class SemanticQuery:
    """
    Complete semantic representation of a user query.

    This object is produced by the Language module and
    consumed by Retrieval.

    The Retrieval module should never know how these
    values have been generated (ONNX, SentenceTransformer,
    HuggingFace, ecc.).

    Future versions may enrich this object without
    requiring changes to Retrieval.
    """

    #
    # Original user query.
    #

    text: str

    #
    # Semantic embedding generated by the language model.
    #
    # None while no encoder has been trained.
    #

    embedding: np.ndarray | None = None

    #
    # Semantic intent.
    #
    # Example:
    #
    #     definition
    #     installation
    #     configuration
    #     comparison
    #

    intent: str = "unknown"

    #
    # Ordered semantic keywords.
    #

    keywords: tuple[str, ...] = ()

    #
    # Semantic entities.
    #

    entities: tuple[str, ...] = ()

    #
    # Semantic expansions.
    #

    expanded_keywords: tuple[str, ...] = ()

    #
    # Confidence produced by Language.
    #

    confidence: float = 0.0

    #
    # Future metadata.
    #

    metadata: dict[str, object] = field(
        default_factory=dict
    )

    @property
    def all_keywords(
        self,
    ) -> tuple[str, ...]:
        """
        Returns every semantic keyword without duplicates.

        Order is preserved.
        """

        result: list[str] = []
        seen: set[str] = set()

        for collection in (
            self.keywords,
            self.entities,
            self.expanded_keywords,
        ):

            for token in collection:

                token = token.strip().lower()

                if not token:
                    continue

                if token in seen:
                    continue

                seen.add(token)
                result.append(token)

        return tuple(result)

    @property
    def has_embedding(
        self,
    ) -> bool:
        """
        Returns True if an embedding is available.
        """

        return self.embedding is not None

    @property
    def embedding_dimension(
        self,
    ) -> int:
        """
        Returns embedding dimension.

        Zero if unavailable.
        """

        if self.embedding is None:
            return 0

        return int(self.embedding.shape[0])

    def metadata_value(
        self,
        key: str,
        default=None,
    ):
        """
        Safe metadata lookup.
        """

        return self.metadata.get(
            key,
            default,
        )