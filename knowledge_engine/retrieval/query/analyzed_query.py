from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from knowledge_engine.retrieval.query.query_intent import QueryIntent


@dataclass(frozen=True, slots=True)
class AnalyzedQuery:
    """
    Structured representation of a user query.

    The QueryAnalyzer transforms a natural language
    question into this object so that downstream
    retrieval components can reason on the user's
    intent instead of raw text alone.

    The object now also carries semantic information
    generated by the Language module.
    """

    #
    # Original question.
    #

    text: str

    #
    # Lexical intent detected by Retrieval.
    #

    intent: QueryIntent = QueryIntent.UNKNOWN

    #
    # Tokenized query.
    #

    tokens: tuple[str, ...] = ()

    #
    # Named entities.
    #

    entities: tuple[str, ...] = ()

    #
    # Boosted tokens.
    #

    boosted_tokens: tuple[str, ...] = ()

    #
    # Expanded tokens.
    #

    expanded_tokens: tuple[str, ...] = ()

    #
    # Lexical confidence.
    #

    confidence: float = 0.0

    # ------------------------------------------------------------------
    # Semantic information (Language module)
    # ------------------------------------------------------------------

    semantic_embedding: np.ndarray | None = None

    semantic_intent: str = "unknown"

    semantic_keywords: tuple[str, ...] = ()

    semantic_entities: tuple[str, ...] = ()

    semantic_expanded_tokens: tuple[str, ...] = ()

    semantic_confidence: float = 0.0

    metadata: dict[str, object] = field(
        default_factory=dict
    )

    @property
    def all_tokens(
        self,
    ) -> tuple[str, ...]:
        """
        Returns every token participating in retrieval.

        Lexical and semantic tokens are merged while
        preserving the original order.
        """

        seen: set[str] = set()
        result: list[str] = []

        for collection in (
            self.tokens,
            self.entities,
            self.boosted_tokens,
            self.expanded_tokens,
            self.semantic_keywords,
            self.semantic_entities,
            self.semantic_expanded_tokens,
        ):

            for token in collection:

                token = token.strip().lower()

                if not token:
                    continue

                if token in seen:
                    continue

                seen.add(token)
                result.append(token)

        return tuple(result)

    @property
    def has_embedding(
        self,
    ) -> bool:

        return self.semantic_embedding is not None

    @property
    def embedding_dimension(
        self,
    ) -> int:

        if self.semantic_embedding is None:
            return 0

        return int(self.semantic_embedding.shape[0])